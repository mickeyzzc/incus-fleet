package nodenet

import (
	"fmt"
	"net"
	"regexp"
	"strconv"
	"strings"
)

// overlayNamePattern keeps overlay identifiers to a conservative character
// set: they become systemd unit names, file names, and nft table names.
var overlayNamePattern = regexp.MustCompile(`^[a-z0-9]([a-z0-9-]{0,30}[a-z0-9])?$`)

// ValidateOverlayName rejects overlay identifiers that could escape the
// fleet-owned configuration paths or nft table namespace.
func ValidateOverlayName(name string) error {
	if !overlayNamePattern.MatchString(name) {
		return fmt.Errorf("%w: overlay name %q must match %s", ErrInvalidRequest, name, overlayNamePattern)
	}
	return nil
}

// ValidateDHCPConfig checks a DHCP definition before writing any file.
func ValidateDHCPConfig(cfg DHCPConfig) error {
	if err := ValidateOverlayName(cfg.Name); err != nil {
		return err
	}
	if err := ValidateName(cfg.Interface); err != nil {
		return err
	}
	start := net.ParseIP(cfg.RangeStart)
	end := net.ParseIP(cfg.RangeEnd)
	gateway := net.ParseIP(cfg.Gateway)
	if start == nil || end == nil {
		return fmt.Errorf("%w: DHCP range %q-%q is invalid", ErrInvalidRequest, cfg.RangeStart, cfg.RangeEnd)
	}
	if gateway == nil {
		return fmt.Errorf("%w: DHCP gateway %q is invalid", ErrInvalidRequest, cfg.Gateway)
	}
	if start.To4() == nil || end.To4() == nil || gateway.To4() == nil {
		return fmt.Errorf("%w: DHCP configuration is IPv4 only", ErrInvalidRequest)
	}
	if compareIP(start, end) > 0 {
		return fmt.Errorf("%w: DHCP range start %s is after end %s", ErrInvalidRequest, cfg.RangeStart, cfg.RangeEnd)
	}
	if cfg.Netmask != "" {
		if ip := net.ParseIP(cfg.Netmask); ip == nil || ip.To4() == nil {
			return fmt.Errorf("%w: DHCP netmask %q is invalid", ErrInvalidRequest, cfg.Netmask)
		}
	}
	if cfg.DNS != "" {
		if ip := net.ParseIP(cfg.DNS); ip == nil {
			return fmt.Errorf("%w: DHCP DNS %q is invalid", ErrInvalidRequest, cfg.DNS)
		}
	}
	return nil
}

// compareIP orders two IPv4 addresses byte-wise.
func compareIP(a, b net.IP) int {
	a4 := a.To4()
	b4 := b.To4()
	for i := 0; i < 4; i++ {
		if a4[i] != b4[i] {
			if a4[i] < b4[i] {
				return -1
			}
			return 1
		}
	}
	return 0
}

// DHCPPaths returns the files written for one overlay DHCP instance.
func DHCPPaths(root, name string) (conf, unit string) {
	prefix := strings.TrimSuffix(root, "/")
	return fmt.Sprintf("%s/etc/dnsmasq.d/fleet-overlay-%s.conf", prefix, name),
		fmt.Sprintf("%s/etc/systemd/system/fleet-overlay-dhcp-%s.service", prefix, name)
}

// DHCPConfigContent renders the dnsmasq configuration for one overlay.
func DHCPConfigContent(cfg DHCPConfig) string {
	var b strings.Builder
	fmt.Fprintf(&b, "# Generated by incus-fleet for overlay %s. Do not edit.\n", cfg.Name)
	fmt.Fprintf(&b, "interface=%s\n", cfg.Interface)
	fmt.Fprintf(&b, "bind-interfaces\n")
	fmt.Fprintf(&b, "except-interface=lo\n")
	fmt.Fprintf(&b, "dhcp-range=%s,%s,%s\n", cfg.RangeStart, cfg.RangeEnd, netmaskOr24(cfg.Netmask))
	fmt.Fprintf(&b, "dhcp-option=option:router,%s\n", cfg.Gateway)
	dns := cfg.DNS
	if dns == "" {
		dns = cfg.Gateway
	}
	fmt.Fprintf(&b, "dhcp-option=option:dns-server,%s\n", dns)
	fmt.Fprintf(&b, "pid-file=/run/fleet-overlay-dhcp-%s.pid\n", cfg.Name)
	fmt.Fprintf(&b, "dhcp-leasefile=/run/fleet-overlay-dhcp-%s.leases\n", cfg.Name)
	b.WriteString("dhcp-authoritative\n")
	return b.String()
}

func netmaskOr24(mask string) string {
	if mask == "" {
		return "255.255.255.0"
	}
	return mask
}

// DHCPUnitContent renders the systemd unit that runs the overlay dnsmasq in
// the foreground so systemd owns its lifecycle.
func DHCPUnitContent(name string) string {
	return fmt.Sprintf(`[Unit]
Description=incus-fleet overlay DHCP for %s
After=network.target

[Service]
Type=simple
ExecStart=/usr/sbin/dnsmasq --keep-in-foreground --conf-file=/etc/dnsmasq.d/fleet-overlay-%s.conf
Restart=on-failure
RestartSec=2

[Install]
WantedBy=multi-user.target
# unit name: fleet-overlay-dhcp-%s.service
`, name, name, name)
}

// WriteDHCPConfig writes the dnsmasq configuration and systemd unit. The
// caller starts the service with StartDHCP.
func (s *Service) WriteDHCPConfig(cfg DHCPConfig) error {
	if err := ValidateDHCPConfig(cfg); err != nil {
		return err
	}
	confPath, unitPath := DHCPPaths("/", cfg.Name)
	if err := s.run.RunStdin("tee", []string{confPath}, DHCPConfigContent(cfg)); err != nil {
		return fmt.Errorf("%w: write dnsmasq config: %v", ErrUnavailable, err)
	}
	if err := s.run.RunStdin("tee", []string{unitPath}, DHCPUnitContent(cfg.Name)); err != nil {
		return fmt.Errorf("%w: write dhcp unit: %v", ErrUnavailable, err)
	}
	return nil
}

// StartDHCP enables and starts the overlay DHCP unit.
func (s *Service) StartDHCP(name string) error {
	if err := ValidateOverlayName(name); err != nil {
		return err
	}
	if _, err := s.run.Run("systemctl", "daemon-reload"); err != nil {
		return fmt.Errorf("%w: systemctl daemon-reload: %v", ErrUnavailable, err)
	}
	unit := "fleet-overlay-dhcp-" + name
	if _, err := s.run.Run("systemctl", "enable", "--now", unit); err != nil {
		return fmt.Errorf("%w: start %s: %v", ErrUnavailable, unit, err)
	}
	return nil
}

// StopDHCP stops and disables the overlay DHCP unit. Missing units are not an
// error so teardown is idempotent.
func (s *Service) StopDHCP(name string) error {
	if err := ValidateOverlayName(name); err != nil {
		return err
	}
	unit := "fleet-overlay-dhcp-" + name
	if _, err := s.run.Run("systemctl", "disable", "--now", unit); err != nil {
		if !strings.Contains(strings.ToLower(err.Error()), "no such file") {
			return fmt.Errorf("%w: stop %s: %v", ErrUnavailable, unit, err)
		}
	}
	confPath, unitPath := DHCPPaths("/", name)
	for _, path := range []string{confPath, unitPath} {
		if _, err := s.run.Run("rm", "-f", path); err != nil {
			return fmt.Errorf("%w: remove %s: %v", ErrUnavailable, path, err)
		}
	}
	return nil
}

// ValidateNAT checks a NAT definition before touching nftables.
func ValidateNAT(cfg NATConfig) error {
	if err := ValidateOverlayName(cfg.Comment); err != nil {
		return err
	}
	_, network, err := net.ParseCIDR(cfg.Source)
	if err != nil || network == nil {
		return fmt.Errorf("%w: NAT source %q is invalid", ErrInvalidRequest, cfg.Source)
	}
	if cfg.OutDevice != "" {
		if err := ValidateName(cfg.OutDevice); err != nil {
			return err
		}
	}
	return nil
}

// natTable returns the fleet-owned nft table for one overlay's NAT rules.
// One table per overlay keeps teardown atomic (drop the table) and avoids
// handle bookkeeping.
func natTable(name string) (string, error) {
	if err := ValidateOverlayName(name); err != nil {
		return "", err
	}
	return "fleet_nat_" + strings.ReplaceAll(name, "-", "_"), nil
}

// AddNAT installs a masquerade rule for the overlay subnet. The table is
// created idempotently so repeated applies converge.
func (s *Service) AddNAT(cfg NATConfig) error {
	if err := ValidateNAT(cfg); err != nil {
		return err
	}
	table, err := natTable(cfg.Comment)
	if err != nil {
		return err
	}

	if _, err := s.run.Run("nft", "add", "table", "ip", table); err != nil {
		// "File exists" is the idempotent case.
		if !strings.Contains(strings.ToLower(err.Error()), "file exists") {
			return fmt.Errorf("%w: create nat table %s: %v", ErrUnavailable, table, err)
		}
	}
	if _, err := s.run.Run("nft", "add", "chain", "ip", table, "postrouting",
		"{", "type", "nat", "hook", "postrouting", "priority", "100", ";", "}"); err != nil {
		if !strings.Contains(strings.ToLower(err.Error()), "file exists") {
			return fmt.Errorf("%w: create nat chain %s: %v", ErrUnavailable, table, err)
		}
	}
	rule := []string{"add", "rule", "ip", table, "postrouting", "ip", "saddr", cfg.Source}
	if cfg.OutDevice != "" {
		rule = append(rule, "oifname", strconv.Quote(cfg.OutDevice))
	}
	rule = append(rule, "masquerade")
	if _, err := s.run.Run("nft", rule...); err != nil {
		// A duplicate rule is the idempotent case.
		if !strings.Contains(strings.ToLower(err.Error()), "file exists") {
			return fmt.Errorf("%w: add nat rule: %v", ErrUnavailable, err)
		}
	}
	return nil
}

// DeleteNAT removes the overlay's entire NAT table.
func (s *Service) DeleteNAT(name string) error {
	table, err := natTable(name)
	if err != nil {
		return err
	}
	if _, err := s.run.Run("nft", "delete", "table", "ip", table); err != nil {
		lower := strings.ToLower(err.Error())
		if !strings.Contains(lower, "no such file") && !strings.Contains(lower, "does not exist") {
			return fmt.Errorf("%w: delete nat table %s: %v", ErrUnavailable, table, err)
		}
	}
	return nil
}
